import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { resolve } from "node:path";
import { CAPABILITIES, capabilityHash, listCliRegistrations, listMcpRegistrations } from "../packages/knowledge-contracts/dist/index.js";

const arg = (name) => process.argv.find((value) => value.startsWith(`--${name}=`))?.slice(name.length + 3);
const id = arg("id") ?? process.env.PENGUIN_RC_ID;
const phase = arg("phase") ?? "RC1";
const previousPath = arg("previous");
const outPath = arg("out");
const root = process.cwd();
const files = ["package.json", "pnpm-lock.yaml", "packages/knowledge-core/dist/index.js", "packages/knowledge-cli/dist/bin.js", "packages/mcp/dist/index.js", "scripts/knowledge-release-gate.mjs", "scripts/knowledge-universal-retrieval-benchmark.mjs", "docs/knowledge-v2/cli-reference.md", "docs/knowledge-v2/mcp-reference.md", "docs/knowledge-v2/capability-matrix.md"];
const hash = createHash("sha256");
for (const file of files) { hash.update(file); hash.update("\0"); if (existsSync(resolve(root, file))) hash.update(readFileSync(resolve(root, file))); }
const fingerprint = hash.digest("hex");
const git = spawnSync("git", ["status", "--porcelain"], { cwd: root, encoding: "utf8" });
const dirty = Boolean(git.stdout?.trim());
const run = (command, args, env = {}) => { const result = spawnSync(command, args, { cwd: root, encoding: "utf8", env: { ...process.env, ...env } }); return { command: [command, ...args].join(" "), exitCode: result.status ?? 1, outputTail: `${result.stdout ?? ""}${result.stderr ?? ""}`.trim().split("\n").slice(-16).join("\n") }; };
const checks = [];
checks.push(run(process.execPath, ["scripts/knowledge-docs-generate.mjs", "--check"]));
checks.push(run(process.execPath, ["scripts/knowledge-surface-parity.mjs", "--gate"]));
checks.push(run(process.execPath, ["scripts/knowledge-package-install-smoke.mjs"]));
checks.push(run(process.execPath, ["scripts/knowledge-sbom.mjs"]));
let gate;
if (process.env.PENGUIN_SKIP_RC_GATE === "true") gate = { skipped: true, reason: "PENGUIN_SKIP_RC_GATE=true" };
else gate = run(process.execPath, ["scripts/knowledge-release-gate.mjs"], { PENGUIN_RC_ID: id ?? "", PENGUIN_BENCHMARK_ROOT: process.env.PENGUIN_BENCHMARK_ROOT ?? "", PENGUIN_REAL_QUESTION_REPORT: process.env.PENGUIN_REAL_QUESTION_REPORT ?? "" });
let previous = null;
if (previousPath && existsSync(resolve(previousPath))) previous = JSON.parse(readFileSync(resolve(previousPath), "utf8"));
const degradedOptional = CAPABILITIES.filter((capability) => !capability.requiredOn.includes("cli") && !capability.requiredOn.includes("mcp")).map((capability) => capability.id);
const report = { generatedAt: new Date().toISOString(), phase, id: id ?? null, capabilityHash: capabilityHash(CAPABILITIES), fingerprint, git: { dirty, status: (git.stdout ?? "").trim() }, surface: { capabilityCount: CAPABILITIES.length, cli: listCliRegistrations().length, mcp: listMcpRegistrations().length }, degradedOptional, checks, gate, independentFromPrevious: phase !== "RC2" ? true : Boolean(previous && previous.fingerprint !== fingerprint), previous: previous ? { id: previous.id, fingerprint: previous.fingerprint } : null };
const blockers = [];
if (!id) blockers.push("RC_ID_REQUIRED");
if (dirty) blockers.push("RC_SOURCE_DIRTY");
if (phase === "RC2" && !previous) blockers.push("RC2_PREVIOUS_REQUIRED");
if (phase === "RC2" && previous?.fingerprint === fingerprint) blockers.push("RC2_ARTIFACT_NOT_INDEPENDENT");
if (!gate.skipped && gate.exitCode !== 0) blockers.push("RELEASE_GATE_FAILED");
if (!checks.every((check) => check.exitCode === 0)) blockers.push("RC_CHECK_FAILED");
report.blockers = blockers;
report.passed = blockers.length === 0;
if (outPath) writeFileSync(resolve(outPath), JSON.stringify(report, null, 2) + "\n");
console.log(JSON.stringify(report, null, 2));
if (!report.passed) process.exitCode = 1;
